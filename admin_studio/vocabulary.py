"""Vocabulary tab of the Admin Studio: the IT/EN labels of the coded values (metadata.vocabulary).

The labels live in scripts/config/vocabulary.json (the source); scripts/build_help.py copies them into the database.
Saving here edits only the it/en labels of existing codes (codes, colours and glossary links are used by the app code)
and reruns build_help → build_app_support_metadata → ux_terminology → title_case_labels, in this order.
The botany.family group is written by build_app_support_metadata.py from the botanical names: it is shown read-only.
"""
import json
from datetime import date
from pathlib import Path

from common import CONFIG, DATA, ROOT, load_json

VOCAB = CONFIG / "vocabulary.json"
APP_LIB = ROOT / "app" / "lib"
PIPELINE = ("build_help.py", "build_app_support_metadata.py", "ux_terminology.py", "title_case_labels.py")


def _is_label(v):
    return isinstance(v, dict) and isinstance(v.get("it"), str) and isinstance(v.get("en"), str)


def _usage(groups):
    """App files that name each group (e.g. db.vocab('category'))."""
    uses = {g: [] for g in groups}
    if not APP_LIB.exists():
        return uses
    for f in APP_LIB.rglob("*.dart"):
        src = f.read_text(encoding="utf-8", errors="replace")
        for g in groups:
            if f"'{g}'" in src:
                uses[g].append(str(f.relative_to(ROOT)).replace("\\", "/"))
    return uses


def payload():
    cfg = load_json(VOCAB)["vocabulary"]
    meta = load_json(DATA / "database.json")["metadata"]
    db_vocab = meta.get("vocabulary") or {}
    uses = _usage(list(cfg) + [k for k in db_vocab if k not in cfg])
    groups = []
    for g, codes in cfg.items():
        groups.append({"group": g, "glossary": codes.get("_glossary"), "used_by": codes.get("_used_by") or [], "editable": True,
                       "app_files": uses.get(g, []),
                       "codes": [{"code": c, "it": v["it"], "en": v["en"], "color": v.get("color_hex"), "marker": v.get("marker")}
                                 for c, v in codes.items() if _is_label(v)]})
    for g, codes in db_vocab.items():               # groups written by other scripts (botany.family): read-only
        if g in cfg or not isinstance(codes, dict):
            continue
        groups.append({"group": g, "glossary": codes.get("_glossary"), "used_by": codes.get("_used_by") or [], "editable": False,
                       "app_files": uses.get(g, []), "note": "Generated by scripts/build_app_support_metadata.py from the botanical names.",
                       "codes": [{"code": c, "it": v["it"], "en": v["en"]} for c, v in codes.items() if _is_label(v)]})
    return {"groups": groups}


def save(data, run_script):
    doc = load_json(VOCAB)
    cfg = doc["vocabulary"]
    for key, v in (data.get("changes") or {}).items():
        g, _, code = key.partition("|")
        if g not in cfg or not _is_label(cfg[g].get(code)):
            raise ValueError(f"unknown vocabulary code: {key}")
        it, en = (v.get("it") or "").strip(), (v.get("en") or "").strip()
        if not (it and en):
            raise ValueError(f"{key}: needs both Italian and English")
        cfg[g][code]["it"], cfg[g][code]["en"] = it, en
    doc["_meta"]["updated"] = date.today().isoformat()
    Path(VOCAB).write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for script in PIPELINE:
        rc, out = run_script(script)
        if rc != 0:
            raise RuntimeError(f"{script}: {out[-500:]}")
